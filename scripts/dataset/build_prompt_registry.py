"""Build a YAML registry of unique task strings from atomic datasets.

Walks ``data/atomic_datasets/<name>/meta/tasks.jsonl`` for every dataset,
collects ``(task_index, task)`` per dataset, and emits a YAML mapping
short-name → {task, source}. The short name is derived from the dataset
name (stripping a leading ``synth_`` prefix). For datasets that ship
multiple tasks, the short name gets an ``_<task_index>`` suffix.

Identical task strings across datasets collapse to one entry: single-task
synth datasets process first so they win the clean short names
(``left_gate``, ``right_gate``, ``center_from_left``, ``center_from_right``);
any other dataset contributing the same string is recorded as
``# also matched by: <dataset>/task_<idx>`` on that entry.

Run::

    python scripts/dataset/build_prompt_registry.py \\
        --datasets-dir data/atomic_datasets \\
        --out configs/prompts/atomic_dataset_prompts.yaml
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path


def _short_name(dataset: str, task_index: int, n_tasks_in_dataset: int) -> str:
    base = dataset
    if base.startswith("synth_"):
        base = base[len("synth_"):]
    if n_tasks_in_dataset == 1:
        return base
    # Multi-task dataset → derive a per-index suffix.
    return f"{base}_{task_index}"


def _read_tasks(jsonl_path: Path) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    with jsonl_path.open() as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            entry = json.loads(line)
            out.append((int(entry["task_index"]), str(entry["task"])))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--datasets-dir", action="append", type=Path, default=None,
                    help="Dataset root(s) to walk; repeatable. Default: "
                         "data/atomic_datasets. Pass the archive dir too "
                         "while legacy prompts are still needed for "
                         "legacy-checkpoint evals.")
    ap.add_argument("--out", default="configs/prompts/atomic_dataset_prompts.yaml", type=Path)
    args = ap.parse_args(argv)
    datasets_dirs = args.datasets_dir or [Path("data/atomic_datasets")]

    for d in datasets_dirs:
        if not d.is_dir():
            print(f"ERROR: {d} not found", file=sys.stderr)
            return 2

    # dataset_name → [(task_index, task), ...]
    raw: dict[str, list[tuple[int, str]]] = {}
    for datasets_dir in datasets_dirs:
        for sub in sorted(datasets_dir.iterdir()):
            if not sub.is_dir():
                continue
            tasks_jsonl = sub / "meta" / "tasks.jsonl"
            if not tasks_jsonl.is_file():
                continue
            raw[sub.name] = _read_tasks(tasks_jsonl)

    # Build short-name map, deduplicating by task **string** so identical
    # prompts across datasets land under one key. Process single-task
    # datasets first so they win the clean short names (e.g. `left_gate`
    # over `dagger-1_real_synth_0`); multi-task datasets fill in any
    # leftover strings and otherwise just contribute a "also matched by"
    # entry on the existing key.
    ordered = sorted(
        raw.items(),
        key=lambda kv: (len(kv[1]) > 1, kv[0]),
    )
    short_to_entry: dict[str, dict] = {}
    task_to_short: dict[str, str] = {}
    duplicates: dict[str, list[str]] = defaultdict(list)
    for dataset, tasks in ordered:
        for task_idx, task in tasks:
            if task in task_to_short:
                duplicates[task_to_short[task]].append(f"{dataset}/task_{task_idx}")
                continue
            short = _short_name(dataset, task_idx, len(tasks))
            # Should not collide given the dedup-by-string above, but guard.
            if short in short_to_entry:
                short = f"{dataset}_{task_idx}"
            short_to_entry[short] = {
                "task": task,
                "source": f"{dataset}/meta/tasks.jsonl (task_index {task_idx})",
            }
            task_to_short[task] = short

    # Emit YAML — handwritten so we control formatting and key order.
    lines: list[str] = []
    lines.append("# Auto-generated by scripts/dataset/build_prompt_registry.py")
    lines.append("# Edit the dataset's meta/tasks.jsonl, then rerun the script.")
    lines.append("# DO NOT edit this file by hand — changes will be overwritten.")
    lines.append("")
    lines.append("prompts:")
    for short in sorted(short_to_entry):
        entry = short_to_entry[short]
        lines.append(f"  {short}:")
        lines.append(f"    task: {json.dumps(entry['task'])}")
        lines.append(f"    source: {entry['source']}")
        if duplicates.get(short):
            lines.append(f"    # also matched by: {', '.join(duplicates[short])}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}  ({len(short_to_entry)} prompts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
